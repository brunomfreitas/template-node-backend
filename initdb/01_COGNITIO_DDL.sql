CREATE TABLE COGNITIO.PRONTUARIO (
  ID_PRONTUARIO SERIAL PRIMARY KEY,
  DS_PRONTUARIO VARCHAR(200),
  DH_INICIO_ATENDIMENTO TIMESTAMP,
  DH_TERMINO_ATENDIMENTO TIMESTAMP,  
  ID_PACIENTE INT NOT NULL REFERENCES COGNITIO.PESSOA(ID_PESSOA),						-- PACIENTE
  NM_RESPONSAVEL VARCHAR(250),
  NR_TELEFONE_RESPONSAVEL VARCHAR(15),
  DS_DECLARACAO_RESPONSAVEL VARCHAR(3000),
  ID_ESCOLA INT REFERENCES COGNITIO.DOMINIO_VALOR(ID_DOMINIO_VALOR),					-- ESCOLAS
  CS_SERIE INT REFERENCES COGNITIO.DOMINIO_VALOR(ID_DOMINIO_VALOR),						-- SERIES
  CS_TURNO INT REFERENCES COGNITIO.DOMINIO_VALOR(ID_DOMINIO_VALOR),						-- TURNOS
  ID_FONOAUDIOLOGO INT NOT NULL REFERENCES COGNITIO.EMPRESA_PESSOA(ID_EMPRESA_PESSOA),	-- FONO
  ID_ASSISTENTE INT REFERENCES COGNITIO.EMPRESA_PESSOA(ID_EMPRESA_PESSOA),				-- ASSISTENTE
  ID_ORGANIZACAO INT NOT NULL REFERENCES COGNITIO.ORGANIZACAO(ID_ORGANIZACAO),
  ID_SITE INT NOT NULL REFERENCES COGNITIO.SITE(ID_SITE),
  ID_ST_PRONTUARIO INT NOT NULL REFERENCES COGNITIO.DOMINIO_VALOR(ID_DOMINIO_VALOR),	-- ST_PRONTUARIO
  ID_ST_ATENDIMENTO INT NOT null REFERENCES COGNITIO.DOMINIO_VALOR(ID_DOMINIO_VALOR),	-- ST_ATENDIMENTO
  ST_ATIVO BOOLEAN DEFAULT true,
  DT_CADASTRO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  DT_ATUALIZACAO TIMESTAMP NULL,
  DT_EXCLUSAO TIMESTAMP NULL
);

